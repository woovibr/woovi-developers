#!/usr/bin/env node
/* eslint-disable no-console */
// Renders every prompt of github.com/woovibr/woovi-prompts as its own doc page,
// so each one is a sidebar item under "Woovi Prompts" (pt-BR in docs/, en in i18n/).
//
//   node scripts/sync-woovi-prompts.mjs [path/to/woovi-prompts]
//
// Without a path it shallow-clones the repo into a temp dir. Re-run it whenever
// a prompt is added or changed upstream; new prompts must also be added to PROMPTS.
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const REPO = 'woovibr/woovi-prompts';
const root = path.resolve(
  path.dirname(new URL(import.meta.url).pathname),
  '..',
);

// sidebar order follows the index of the upstream README
const PROMPTS = [
  ['charge-pix', 'Cobrança Pix (charge)', 'Pix charge'],
  ['pix-qrcode-static', 'QR Code Pix estático', 'Static Pix QR Code'],
  ['pix-automatico', 'Pix Automático', 'Pix Automático'],
  [
    'pixout-with-pix-key',
    'PixOut com consulta de chave',
    'PixOut with key lookup',
  ],
  [
    'pixout-without-pix-key',
    'PixOut sem consulta de chave',
    'PixOut without key lookup',
  ],
  ['refund', 'Reembolso', 'Refund'],
  ['customer', 'Cliente (customer)', 'Customer'],
  ['webhooks', 'Webhooks', 'Webhooks'],
  ['subaccount', 'Subcontas e Split', 'Subaccounts and Split'],
  ['partner', 'Partner', 'Partner'],
  ['campaign-pix-key', 'Campaign Pix Key', 'Campaign Pix Key'],
  ['ecommerce-woocommerce', 'WooCommerce', 'WooCommerce'],
  ['ecommerce-magento1', 'Magento 1', 'Magento 1'],
  ['ecommerce-magento2', 'Magento 2', 'Magento 2'],
  ['ecommerce-opencart', 'OpenCart', 'OpenCart'],
  [
    'ecommerce-others',
    'Outras plataformas de e-commerce',
    'Other e-commerce platforms',
  ],
  ['javascript-plugin', 'JavaScript Plugin', 'JavaScript Plugin'],
  ['react-sdk', 'React SDK', 'React SDK'],
  ['n8n-zapier', 'n8n / Zapier / Make', 'n8n / Zapier / Make'],
  ['whatsapp', 'WhatsApp', 'WhatsApp'],
  ['cashback', 'Cashback', 'Cashback'],
  [
    'auth-and-security',
    'Autenticação e segurança',
    'Authentication and security',
  ],
];

const LOCALES = [
  {
    src: 'prompts',
    out: 'docs/woovi-prompts',
    label: (p) => p[1],
    note: (url) =>
      `:::tip Como usar\n\nCopie o prompt abaixo inteiro e cole na sua ferramenta de IA (Claude, ChatGPT, Cursor, Copilot...). Fonte: [${REPO}](${url}).\n\n:::`,
  },
  {
    src: 'prompts-en',
    out: 'i18n/en/docusaurus-plugin-content-docs/current/woovi-prompts',
    label: (p) => p[2],
    note: (url) =>
      `:::tip How to use\n\nCopy the whole prompt below and paste it into your AI tool (Claude, ChatGPT, Cursor, Copilot...). Source: [${REPO}](${url}).\n\n:::`,
  },
];

const getSource = () => {
  if (process.argv[2]) return path.resolve(process.argv[2]);
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'woovi-prompts-'));
  execFileSync('git', [
    'clone',
    '--quiet',
    '--depth',
    '1',
    `https://github.com/${REPO}.git`,
    dir,
  ]);
  return dir;
};

const yamlString = (value) => JSON.stringify(value);

const source = getSource();

const missing = fs
  .readdirSync(path.join(source, 'prompts'))
  .map((file) => path.basename(file, '.md'))
  .filter((id) => !PROMPTS.some(([known]) => known === id));
if (missing.length) {
  console.error(`prompts not listed in PROMPTS: ${missing.join(', ')}`);
  process.exit(1);
}

for (const locale of LOCALES) {
  const outDir = path.join(root, locale.out);
  fs.mkdirSync(outDir, { recursive: true });

  PROMPTS.forEach((prompt, index) => {
    const [id] = prompt;
    const markdown = fs.readFileSync(
      path.join(source, locale.src, `${id}.md`),
      'utf-8',
    );
    const [heading, ...body] = markdown.split('\n');
    const title = heading.replace(/^#\s+/, '').trim();
    const url = `https://github.com/${REPO}/blob/main/${locale.src}/${id}.md`;

    const page = [
      '---',
      `id: ${id}`,
      `title: ${yamlString(title)}`,
      `sidebar_label: ${yamlString(locale.label(prompt))}`,
      `sidebar_position: ${index + 1}`,
      // the prompts are plain markdown with JSX-looking snippets (<APP_ID>, {id}) in prose
      'format: md',
      'tags:',
      '  - prompts',
      '  - ai',
      '---',
      '',
      `<!-- generated by scripts/sync-woovi-prompts.mjs from ${url} — do not edit by hand -->`,
      '',
      locale.note(url),
      '',
      body.join('\n').trim(),
      '',
    ].join('\n');

    fs.writeFileSync(path.join(outDir, `${id}.md`), page);
  });

  console.log(`${PROMPTS.length} prompts -> ${locale.out}`);
}
